// MARK: - Clipboard history

/// The last things you copied (text, images, files), kept in memory only: nothing is written to
/// disk and the list is gone when Coucou quits. Passwords and other "concealed" or "transient"
/// clipboard contents (the nspasteboard.org convention used by password managers) are never kept.
/// Polls the pasteboard's change count twice a second (a counter read, no copying).
@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    enum Kind: Equatable { case text(String), image(NSImage), files([URL]) }

    struct Item: Identifiable, Equatable {
        let id = UUID()
        let kind: Kind
        let copied: Date
        let app: String

        static func == (a: Item, b: Item) -> Bool { a.id == b.id }
    }

    @Published private(set) var items: [Item] = []
    private let maxItems = 25
    private var lastChange = NSPasteboard.general.changeCount
    /// Change count of what we put back ourselves, so it isn't recorded twice.
    private var ownChange: Int?
    private var timer: Timer?

    private static let skipped: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    private init() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            Task { @MainActor in ClipboardHistory.shared.check() }
        }
    }

    private func check() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        if ownChange == board.changeCount { return }
        let types = Set(board.types ?? [])
        guard types.isDisjoint(with: Self.skipped) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName ?? ""

        let kind: Kind
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            kind = .files(urls)
        } else if let text = board.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            // The same text again moves to the top instead of repeating
            items.removeAll { if case .text(let t) = $0.kind { return t == text } else { return false } }
            kind = .text(text)
        } else if let image = NSImage(pasteboard: board) {
            kind = .image(image)
        } else {
            return
        }
        items.insert(Item(kind: kind, copied: Date(), app: app), at: 0)
        if items.count > maxItems { items.removeLast(items.count - maxItems) }
    }

    /// Puts an item back on the clipboard (ready for ⌘V) and moves it to the top.
    func copy(_ item: Item) {
        let board = NSPasteboard.general
        board.clearContents()
        switch item.kind {
        case .text(let t):      board.setString(t, forType: .string)
        case .image(let img):   board.writeObjects([img])
        case .files(let urls):  board.writeObjects(urls as [NSURL])
        }
        ownChange = board.changeCount
        lastChange = board.changeCount
        items.removeAll { $0.id == item.id }
        items.insert(Item(kind: item.kind, copied: Date(), app: item.app), at: 0)
        SoundEngine.shared.play("blip")
        NSHapticFeedbackManager.defaultPerformer.perform(.alignment, performanceTime: .now)
    }

    func remove(_ item: Item) { items.removeAll { $0.id == item.id } }
    func clear() { items.removeAll() }
}

// MARK: - Clipboard tab

struct ClipboardView: View {
    @ObservedObject var state: AppState
    @ObservedObject private var history = ClipboardHistory.shared
    @State private var copiedId: UUID?

    private let accent = Color(hex: "#60A5FA")

    var body: some View {
        ZStack(alignment: .topLeading) {
            CardBackground(wash: nil)
            VStack(alignment: .leading, spacing: 8) {
                HStack(spacing: 6) {
                    Circle().fill(accent).frame(width: 7, height: 7)
                    Text("Clipboard")
                        .font(.system(size: 12, weight: .semibold))
                        .foregroundColor(Color(hex: "#F5F6F8"))
                    Text("click to copy again")
                        .font(.system(size: 10.5))
                        .foregroundColor(Color(hex: "#6B7079"))
                    Spacer(minLength: 4)
                    if !history.items.isEmpty {
                        Button(String(localized: "Clear")) { withAnimation { history.clear() } }
                            .font(.system(size: 10.5, weight: .medium))
                            .foregroundColor(Color(hex: "#8E939C"))
                            .buttonStyle(.plain)
                    }
                }
                if history.items.isEmpty {
                    VStack(spacing: 6) {
                        Spacer(minLength: 0)
                        Image(systemName: "doc.on.clipboard")
                            .font(.system(size: 20))
                            .foregroundColor(accent.opacity(0.7))
                        Text("Copy something: it shows up here.")
                            .font(.system(size: 11.5))
                            .foregroundColor(Color(hex: "#8E939C"))
                        Text("Kept until Coucou quits. Passwords are never kept.")
                            .font(.system(size: 10.5))
                            .foregroundColor(Color(hex: "#6B7079"))
                        Spacer(minLength: 0)
                    }
                    .frame(maxWidth: .infinity, maxHeight: .infinity)
                } else {
                    ScrollView(.vertical, showsIndicators: false) {
                        VStack(alignment: .leading, spacing: 4) {
                            ForEach(history.items) { item in
                                ClipboardRow(item: item, copied: copiedId == item.id, accent: accent) {
                                    history.copy(item)
                                    withAnimation(.snappy) { copiedId = history.items.first?.id }
                                    DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) {
                                        withAnimation { copiedId = nil }
                                    }
                                }
                            }
                        }
                        .padding(.vertical, 2)
                        .animation(.spring(response: 0.3, dampingFraction: 0.85), value: history.items)
                    }
                }
            }
            .padding(.leading, 84)
            .padding(.trailing, 16)
            .padding(.top, 12)
            .padding(.bottom, 10)
        }
        .padding(.bottom, 10)
    }
}

struct ClipboardRow: View {
    let item: ClipboardHistory.Item
    let copied: Bool
    let accent: Color
    let action: () -> Void
    @State private var hovered = false

    var body: some View {
        Button(action: action) {
            HStack(spacing: 9) {
                preview
                VStack(alignment: .leading, spacing: 2) {
                    Text(title)
                        .font(.system(size: 12))
                        .foregroundColor(Color(hex: "#F1F2F4"))
                        .lineLimit(2).truncationMode(.tail)
                        .multilineTextAlignment(.leading)
                    Text(meta)
                        .font(.system(size: 9.5))
                        .foregroundColor(Color(hex: "#6B7079"))
                }
                Spacer(minLength: 4)
                if copied {
                    Label(String(localized: "Copied"), systemImage: "checkmark")
                        .font(.system(size: 10, weight: .semibold))
                        .foregroundColor(accent)
                        .transition(.scale.combined(with: .opacity))
                } else if hovered {
                    Image(systemName: "doc.on.doc")
                        .font(.system(size: 10))
                        .foregroundColor(Color(hex: "#8E939C"))
                }
            }
            .padding(.horizontal, 8).padding(.vertical, 6)
            .background(RoundedRectangle(cornerRadius: 9)
                .fill(copied ? accent.opacity(0.15) : Color.white.opacity(hovered ? 0.08 : 0.04)))
            .contentShape(Rectangle())
        }
        .buttonStyle(NowPlayingPressStyle())
        .onHover { h in withAnimation(.easeOut(duration: 0.12)) { hovered = h } }
        .contextMenu {
            Button(String(localized: "Copy")) { action() }
            if case .text(let t) = item.kind {
                Button(String(localized: "Ask Claude")) { ClaudeChatDraft.open(with: t) }
                Button(String(localized: "Save as a note")) { NotesStore.shared.add(t, remindAt: nil) }
            }
            Divider()
            Button(String(localized: "Remove")) { ClipboardHistory.shared.remove(item) }
        }
    }

    @ViewBuilder private var preview: some View {
        switch item.kind {
        case .text:
            Image(systemName: "text.alignleft")
                .font(.system(size: 11))
                .foregroundColor(accent)
                .frame(width: 26, height: 26)
                .background(RoundedRectangle(cornerRadius: 6).fill(accent.opacity(0.12)))
        case .image(let img):
            Image(nsImage: img)
                .resizable().aspectRatio(contentMode: .fill)
                .frame(width: 26, height: 26)
                .clipShape(RoundedRectangle(cornerRadius: 6))
        case .files(let urls):
            Image(nsImage: NSWorkspace.shared.icon(forFile: urls[0].path))
                .resizable()
                .frame(width: 26, height: 26)
        }
    }

    private var title: String {
        switch item.kind {
        case .text(let t):
            return t.trimmingCharacters(in: .whitespacesAndNewlines)
                .components(separatedBy: .newlines).filter { !$0.isEmpty }.joined(separator: " ⏎ ")
        case .image(let img):
            return String(localized: "Image · \(Int(img.size.width))×\(Int(img.size.height))")
        case .files(let urls):
            return urls.count == 1 ? urls[0].lastPathComponent
                                   : String(localized: "\(urls[0].lastPathComponent) + \(urls.count - 1) more")
        }
    }

    private var meta: String {
        let time = item.copied.formatted(date: .omitted, time: .shortened)
        return item.app.isEmpty ? time : "\(item.app) · \(time)"
    }
}
